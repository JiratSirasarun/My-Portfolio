export function getProduct(id: string): Product | undefined {
  return products.find((p) => p.id === id)
}

export function getProductsByCategory(slug: string): Product[] {
  return products.filter((p) => p.category === slug)
}

/** Search enforces the "specific, curated SKU range" constraint from the
 * customer-journey doc: only items flagged `searchable` may surface here,
 * not the full catalog. */
export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return products.filter((p) => p.searchable && p.name.toLowerCase().includes(q))
}
